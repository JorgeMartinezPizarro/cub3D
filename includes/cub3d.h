# define TILE_EMPTY			0
# define TILE_WALL			1
# define TILE_DOOR			2
# define TILE_DOOR_OPEN   	3
# define TILE_DOOR_HALF		4

// DOOR TRANSPARENCY: this project's vendored minilibx (mlx_xpm.c) maps every
// "c None" xpm pixel to this exact 32bpp value (see mlx_rgb.c: {"none", -1}
// and mlx_xpm.c: if (col == -1) col = 0xFF000000), so no texture edits needed
# define DOOR_ALPHA_KEY		0xFF000000

// DOOR ANIMATION: closed/half/open textures shown in sequence while the
// door tile is TILE_DOOR_HALF; DOOR_FRAME_MS is how long each one is shown
# define DOOR_FRAME_MS		133
# define DOOR_ANIM_MS		399

// WIN: once the last door finishes opening, wait this long (with the HUD
// already showing n/n) before switching to the end screen
# define WIN_DELAY_MS		400

// SCORE: best times are stored XOR'd and hex-encoded so the file is not
// trivially editable in a plain text editor
# define SCORES_PATH		"scores.dat"
# define SCORE_XOR_KEY		0x5A
# define SCORE_MAP_COUNT	10

// START SCREEN: miniature map preview box + the 4 corner key icons
