// TEXT: put_centered() blits glyphs from a monospaced spritesheet
// (textures/font.xpm, generated by scripts/gen_font_xpm.py) instead of
// using mlx_string_put, whose X core "fixed" font is unreadably small on
// 4K screens. Glyph (row, col) in the sheet = (idx / FONT_COLS, idx %
// FONT_COLS) where idx = char - FONT_FIRST_CHAR.
# define FONT_PATH "textures/font.xpm"
# define FONT_CELL_W 14
# define FONT_CELL_H 24
# define FONT_COLS 16
# define FONT_FIRST_CHAR 32
# define FONT_GLYPH_COUNT 95
# define FONT_CHAR_W FONT_CELL_W
// extra leading added on top of the scaled glyph height by font_line_h(),
// as a percentage, so lines of text never overlap the one below them
# define FONT_LINE_LEADING 30

// HUD: size in pixels of each digit sprite drawn for the doors-open counter
# define HUD_DIGIT_SIZE 128
# define HUD_PAD 8
# define COLOR_PLAYER 0x00FFFFFF

